def add(a, b):
    return a + b

def modulus(a, b):
    return a % b  # This function calculates the remainder of a divided by b

def subtract(a, b):
    return a - b

def power(a, b):
    return a ** b

def multiply(a, b):
    return a * b

def root(a, n):
    return a ** (1/n)

def divide(a, b):
    return a / b

